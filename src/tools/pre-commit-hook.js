/**
 * Pre-commit Hook Generator
 *
 * Generates git hooks to prevent committing security issues:
 * - Hardcoded secrets
 * - Sensitive files
 * - Debug code
 */

import { writeFile, mkdir, chmod, access, readFile } from 'fs/promises';
import { join } from 'path';

export class PreCommitHookGenerator {
  constructor(projectPath) {
    this.projectPath = projectPath;
  }

  /**
   * Generate and install pre-commit hook
   */
  async generate(options = {}) {
    const {
      checkSecrets = true,
      checkEnvFiles = true,
      checkDebugCode = true,
      checkLargeFiles = true,
      maxFileSize = 5 * 1024 * 1024, // 5MB
      customPatterns = []
    } = options;

    const hookContent = this.buildHookScript({
      checkSecrets,
      checkEnvFiles,
      checkDebugCode,
      checkLargeFiles,
      maxFileSize,
      customPatterns
    });

    return {
      hookContent,
      instructions: this.getInstructions(),
      huskyConfig: this.getHuskyConfig(),
      lintStagedConfig: this.getLintStagedConfig()
    };
  }

  /**
   * Build the pre-commit hook script
   */
  buildHookScript(options) {
    const script = `#!/bin/sh
#
# Guardian-Agent Pre-commit Hook
# Prevents committing security issues
#
# Generated by Guardian-Agent security scanner
# https://github.com/naieum/ChiefWiggum
#

set -e

echo "🛡️  Guardian-Agent: Running security checks..."

# Colors for output
RED='\\033[0;31m'
GREEN='\\033[0;32m'
YELLOW='\\033[1;33m'
NC='\\033[0m' # No Color

ERRORS=0

${options.checkSecrets ? this.getSecretCheckScript() : '# Secret check disabled'}

${options.checkEnvFiles ? this.getEnvFileCheckScript() : '# Env file check disabled'}

${options.checkDebugCode ? this.getDebugCodeCheckScript() : '# Debug code check disabled'}

${options.checkLargeFiles ? this.getLargeFileCheckScript(options.maxFileSize) : '# Large file check disabled'}

${options.customPatterns.length > 0 ? this.getCustomPatternScript(options.customPatterns) : '# No custom patterns'}

# Final check
if [ $ERRORS -gt 0 ]; then
    echo ""
    echo -e "\${RED}❌ Pre-commit check failed with $ERRORS error(s)\${NC}"
    echo ""
    echo "To bypass this check (not recommended), use: git commit --no-verify"
    exit 1
fi

echo -e "\${GREEN}✅ All security checks passed\${NC}"
exit 0
`;

    return script;
  }

  /**
   * Get secret detection script
   */
  getSecretCheckScript() {
    return `
#
# Check for hardcoded secrets
#
echo "Checking for hardcoded secrets..."

# Get list of staged files
STAGED_FILES=$(git diff --cached --name-only --diff-filter=ACM)

# Secret patterns to check
SECRET_PATTERNS=(
    # AWS
    'AKIA[0-9A-Z]{16}'
    # GitHub
    'gh[ps]_[A-Za-z0-9_]{36,}'
    'gho_[A-Za-z0-9_]{36,}'
    # Stripe
    'sk_live_[0-9a-zA-Z]{24,}'
    'sk_test_[0-9a-zA-Z]{24,}'
    # Slack
    'xox[baprs]-[0-9A-Za-z-]+'
    # Private keys
    '-----BEGIN (RSA |EC |DSA )?PRIVATE KEY-----'
    # Generic API keys (be careful with false positives)
    'api[_-]?key["\\'\\s]*[:=]["\\'\\s]*[A-Za-z0-9_-]{20,}'
    # Generic secrets
    'secret[_-]?key["\\'\\s]*[:=]["\\'\\s]*[A-Za-z0-9_-]{20,}'
    # JWT tokens
    'eyJ[A-Za-z0-9_-]*\\.eyJ[A-Za-z0-9_-]*\\.[A-Za-z0-9_-]*'
    # Google API
    'AIza[0-9A-Za-z_-]{35}'
    # OpenAI
    'sk-[A-Za-z0-9]{48}'
)

for FILE in $STAGED_FILES; do
    # Skip binary files and certain paths
    if [[ "$FILE" =~ \\.(jpg|jpeg|png|gif|ico|woff|woff2|ttf|eot|pdf|zip)$ ]]; then
        continue
    fi
    if [[ "$FILE" =~ ^(node_modules|dist|build|coverage)/ ]]; then
        continue
    fi
    if [[ "$FILE" =~ \\.example$ ]] || [[ "$FILE" =~ \\.sample$ ]]; then
        continue
    fi

    for PATTERN in "\${SECRET_PATTERNS[@]}"; do
        if git show ":$FILE" 2>/dev/null | grep -qE "$PATTERN"; then
            echo -e "\${RED}❌ Potential secret found in: $FILE\${NC}"
            echo "   Pattern: $PATTERN"
            ERRORS=$((ERRORS + 1))
        fi
    done
done
`;
  }

  /**
   * Get env file check script
   */
  getEnvFileCheckScript() {
    return `
#
# Check for .env files being committed
#
echo "Checking for .env files..."

ENV_FILES=$(git diff --cached --name-only | grep -E '^\\.env(\\..*)?$' | grep -v '\\.example$' | grep -v '\\.sample$' || true)

if [ -n "$ENV_FILES" ]; then
    echo -e "\${RED}❌ Attempting to commit .env file(s):\${NC}"
    echo "$ENV_FILES"
    echo ""
    echo "These files should be in .gitignore. If you really need to commit them,"
    echo "use 'git commit --no-verify' (not recommended)"
    ERRORS=$((ERRORS + 1))
fi
`;
  }

  /**
   * Get debug code check script
   */
  getDebugCodeCheckScript() {
    return `
#
# Check for debug code
#
echo "Checking for debug code..."

STAGED_FILES=$(git diff --cached --name-only --diff-filter=ACM | grep -E '\\.(js|jsx|ts|tsx|py|rb)$' || true)

DEBUG_PATTERNS=(
    'console\\.log'
    'debugger'
    'binding\\.pry'
    'import pdb'
    'breakpoint\\(\\)'
    '\\.only\\('  # test.only, describe.only
)

for FILE in $STAGED_FILES; do
    for PATTERN in "\${DEBUG_PATTERNS[@]}"; do
        # Check staged content, not working directory
        MATCHES=$(git show ":$FILE" 2>/dev/null | grep -n "$PATTERN" || true)
        if [ -n "$MATCHES" ]; then
            echo -e "\${YELLOW}⚠️  Debug code found in $FILE:\${NC}"
            echo "$MATCHES" | head -3
            # Warning only, not blocking
        fi
    done
done
`;
  }

  /**
   * Get large file check script
   */
  getLargeFileCheckScript(maxSize) {
    const maxSizeKB = Math.round(maxSize / 1024);
    return `
#
# Check for large files
#
echo "Checking for large files..."

STAGED_FILES=$(git diff --cached --name-only --diff-filter=ACM)
MAX_SIZE=${maxSizeKB}  # KB

for FILE in $STAGED_FILES; do
    if [ -f "$FILE" ]; then
        SIZE=$(wc -c < "$FILE" | tr -d ' ')
        SIZE_KB=$((SIZE / 1024))

        if [ $SIZE_KB -gt $MAX_SIZE ]; then
            echo -e "\${YELLOW}⚠️  Large file detected: $FILE (\${SIZE_KB}KB > \${MAX_SIZE}KB)\${NC}"
            echo "   Consider using Git LFS for large files"
            # Warning only by default
        fi
    fi
done
`;
  }

  /**
   * Get custom pattern check script
   */
  getCustomPatternScript(patterns) {
    const patternChecks = patterns.map(p => `
    if git show ":$FILE" 2>/dev/null | grep -qE "${p.pattern}"; then
        echo -e "\${RED}❌ ${p.message || 'Custom pattern matched'} in: $FILE\${NC}"
        ERRORS=$((ERRORS + 1))
    fi`).join('\n');

    return `
#
# Custom pattern checks
#
echo "Running custom pattern checks..."

STAGED_FILES=$(git diff --cached --name-only --diff-filter=ACM)

for FILE in $STAGED_FILES; do
${patternChecks}
done
`;
  }

  /**
   * Get installation instructions
   */
  getInstructions() {
    return {
      manual: `
# Manual Installation

1. Create the hooks directory if it doesn't exist:
   mkdir -p .git/hooks

2. Create the pre-commit hook:
   cat > .git/hooks/pre-commit << 'EOF'
   [paste hook content here]
   EOF

3. Make it executable:
   chmod +x .git/hooks/pre-commit

4. Test it:
   git add .
   git commit -m "test"
      `.trim(),

      husky: `
# Using Husky (recommended for team projects)

1. Install Husky:
   npm install husky --save-dev

2. Initialize Husky:
   npx husky init

3. Add the pre-commit hook:
   echo 'npx guardian-agent pre-commit' > .husky/pre-commit

4. Commit the hook:
   git add .husky/pre-commit
   git commit -m "Add security pre-commit hook"
      `.trim(),

      leftHook: `
# Using Lefthook (alternative to Husky)

1. Install Lefthook:
   npm install lefthook --save-dev

2. Create lefthook.yml:
   pre-commit:
     parallel: true
     commands:
       guardian-secrets:
         run: npx guardian-agent check-secrets
         stage_fixed: true

3. Install hooks:
   npx lefthook install
      `.trim()
    };
  }

  /**
   * Get Husky configuration
   */
  getHuskyConfig() {
    return {
      'package.json': {
        scripts: {
          prepare: 'husky'
        },
        devDependencies: {
          husky: '^9.0.0'
        }
      },
      '.husky/pre-commit': `#!/usr/bin/env sh
. "$(dirname -- "$0")/_/husky.sh"

# Guardian-Agent security checks
echo "🛡️  Running Guardian-Agent security checks..."

# Check for secrets
npx guardian-agent check-secrets --staged

# Check for .env files
if git diff --cached --name-only | grep -qE '^\\.env(\\..*)?$' | grep -v '\\.example$'; then
  echo "❌ Attempting to commit .env files"
  exit 1
fi

echo "✅ Security checks passed"
`
    };
  }

  /**
   * Get lint-staged configuration
   */
  getLintStagedConfig() {
    return {
      'lint-staged.config.js': `
module.exports = {
  '*': [
    // Check for secrets in all files
    (files) => \`npx guardian-agent check-secrets \${files.join(' ')}\`,
  ],
  '*.{js,jsx,ts,tsx}': [
    // Additional code checks
    'eslint --fix',
    'prettier --write',
  ],
  '.env*': [
    // Block .env files (except .example)
    (files) => {
      const blocked = files.filter(f => !f.includes('.example'));
      if (blocked.length > 0) {
        throw new Error(\`Cannot commit: \${blocked.join(', ')}\`);
      }
      return [];
    },
  ],
};
      `.trim()
    };
  }

  /**
   * Install the hook directly
   */
  async install(options = {}) {
    const gitDir = join(this.projectPath, '.git');
    const hooksDir = join(gitDir, 'hooks');

    // Check if this is a git repo
    try {
      await access(gitDir);
    } catch {
      return {
        success: false,
        error: 'Not a git repository. Initialize git first: git init'
      };
    }

    // Create hooks directory
    try {
      await mkdir(hooksDir, { recursive: true });
    } catch {
      // Directory exists
    }

    // Generate and write hook
    const { hookContent } = await this.generate(options);
    const hookPath = join(hooksDir, 'pre-commit');

    // Check for existing hook
    let existingHook = null;
    try {
      existingHook = await readFile(hookPath, 'utf-8');
    } catch {
      // No existing hook
    }

    if (existingHook && !options.force) {
      return {
        success: false,
        error: 'Pre-commit hook already exists. Use force: true to overwrite.',
        existingHook: existingHook.substring(0, 200) + '...'
      };
    }

    // Write hook
    await writeFile(hookPath, hookContent);
    await chmod(hookPath, 0o755);

    return {
      success: true,
      message: 'Pre-commit hook installed successfully',
      path: hookPath
    };
  }
}

export default PreCommitHookGenerator;
